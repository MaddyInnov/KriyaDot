// CA-22: GitHub-native agent pack — KriyaDot side.
//
// Flow: a GitHub issue/PR comment containing `/kriyadot …` arrives as a
// webhook (issue_comment / pull_request_review_comment). This module:
//   1. verifies the GitHub HMAC signature (same timing-safe pattern as
//      routine-hooks.ts),
//   2. parses the `/kriyadot` command (run / review / help),
//   3. hands `run` commands to the EXISTING webhooks→routines path via an
//      injected dispatcher (the routine hook store / run executor wired
//      in index.ts — see the Wave-6 wiring note),
//   4. for `review`, produces a governed PR review: the review body is
//      generated by an injected reviewer and posted ONLY through an
//      injected poster that the host binds to the approval-gated
//      POST /api/github/pr machinery (github.ts submitReview). This
//      module itself never calls GitHub and never holds a token.
//
// Everything is mock-verified in tests with fake webhook payloads.

import { createHmac, timingSafeEqual } from 'node:crypto';
import { Router } from 'express';
import type { Request, Response } from 'express';

export function verifyGithubSignature(signature: string | undefined, rawBody: Buffer, secret: string): boolean {
  if (!signature) return false;
  const hex = signature.startsWith('sha256=') ? signature.slice(7) : signature;
  if (!/^[0-9a-fA-F]{64}$/.test(hex)) return false;
  const expected = createHmac('sha256', secret).update(rawBody).digest('hex');
  const a = Buffer.from(hex.toLowerCase());
  const b = Buffer.from(expected);
  return a.length === b.length && timingSafeEqual(a, b);
}

export interface KriyaDotCommand {
  kind: 'run' | 'review' | 'help' | 'unknown';
  /** Free-text task after the verb (for `run`). */
  task: string;
  raw: string;
}

const COMMAND_RE = /(?:^|\n)\s*\/kriyadot\s+([a-z-]+)?\s*([\s\S]*?)\s*(?:\n|$)/i;

/** Extract a `/kriyadot …` command from a comment body; null when absent. */
export function parseKriyaDotCommand(body: string): KriyaDotCommand | null {
  if (typeof body !== 'string' || !body.includes('/kriyadot')) return null;
  const m = COMMAND_RE.exec(body);
  if (!m) return null;
  const verb = (m[1] ?? 'run').toLowerCase();
  const rest = (m[2] ?? '').trim();
  if (verb === 'review') return { kind: 'review', task: rest, raw: body };
  if (verb === 'help') return { kind: 'help', task: '', raw: body };
  if (verb === 'run') return { kind: 'run', task: rest, raw: body };
  // `/kriyadot <free text>` with no known verb is a run of that text.
  if (!m[1]) return { kind: 'run', task: rest, raw: body };
  return { kind: 'unknown', task: rest, raw: body };
}

export interface GithubCommentEvent {
  repo: string;
  number: number;
  isPullRequest: boolean;
  commentId: number | string;
  author: string;
  body: string;
  htmlUrl?: string;
}

/** Normalize a fake/real GitHub webhook payload into a comment event. */
export function parseGithubCommentPayload(payload: unknown): GithubCommentEvent | null {
  if (typeof payload !== 'object' || payload === null) return null;
  const p = payload as Record<string, any>;
  const comment = p.comment;
  if (!comment || typeof comment.body !== 'string') return null;
  const issue = p.issue ?? p.pull_request ?? {};
  const repo = p.repository?.full_name;
  if (typeof repo !== 'string' || typeof issue.number !== 'number') return null;
  return {
    repo,
    number: issue.number,
    isPullRequest: Boolean(issue.pull_request) || Boolean(p.pull_request),
    commentId: comment.id ?? 'unknown',
    author: comment.user?.login ?? 'unknown',
    body: comment.body,
    htmlUrl: comment.html_url,
  };
}

export interface GithubAgentDeps {
  /** Webhook secret (GitHub webhook secret for this endpoint). */
  secret: string;
  /** Dispatch a governed routine/agent run — host binds the existing routine-hooks executor. */
  dispatchRun: (input: { repo: string; number: number; task: string; author: string; event: GithubCommentEvent }) => Promise<{ runId?: string }>;
  /** Generate a review body for a PR (injected; mock in tests, LLM-backed in host). */
  reviewPullRequest?: (input: { repo: string; number: number; instruction: string }) => Promise<{ body: string; event: 'COMMENT' | 'APPROVE' | 'REQUEST_CHANGES' }>;
  /** Post the review — host binds this to the approval-gated github.ts submitReview path. */
  postReview?: (input: { repo: string; number: number; body: string; event: 'COMMENT' | 'APPROVE' | 'REQUEST_CHANGES' }) => Promise<unknown>;
  audit?: (action: string, fields: Record<string, unknown>) => void;
}

export interface GithubAgentResult {
  handled: boolean;
  reason?: string;
  command?: KriyaDotCommand;
  runId?: string;
}

/** Pure handler (no HTTP) — the router below is a thin shell over it. */
export async function handleGithubCommentWebhook(
  payload: unknown,
  deps: GithubAgentDeps,
): Promise<GithubAgentResult> {
  const event = parseGithubCommentPayload(payload);
  if (!event) return { handled: false, reason: 'not a comment payload' };
  const command = parseKriyaDotCommand(event.body);
  if (!command) return { handled: false, reason: 'no /kriyadot command' };
  if (command.kind === 'help' || command.kind === 'unknown') {
    deps.audit?.('github-agent.command.ignored', { repo: event.repo, number: event.number, kind: command.kind });
    return { handled: true, reason: command.kind, command };
  }
  if (command.kind === 'review') {
    if (!event.isPullRequest) return { handled: false, reason: 'review command on a non-PR issue', command };
    if (!deps.reviewPullRequest || !deps.postReview) return { handled: false, reason: 'review path not wired', command };
    const review = await deps.reviewPullRequest({ repo: event.repo, number: event.number, instruction: command.task });
    // Posting goes through the host's approval-gated poster — never direct.
    await deps.postReview({ repo: event.repo, number: event.number, body: review.body, event: review.event });
    deps.audit?.('github-agent.review.posted', { repo: event.repo, number: event.number, event: review.event });
    return { handled: true, command };
  }
  const { runId } = await deps.dispatchRun({ repo: event.repo, number: event.number, task: command.task, author: event.author, event });
  deps.audit?.('github-agent.run.dispatched', { repo: event.repo, number: event.number, runId: runId ?? null });
  return { handled: true, command, runId };
}

/**
 * Register-style router. Mount (wiring note):
 *   app.use('/api/github-agent', registerGithubAgentRoutes(deps))
 * Expects the RAW body for HMAC verification: mount with
 * express.raw({ type: 'application/json' }) on this path, or pass
 * `req.rawBody` when the host captured it.
 */
export function registerGithubAgentRoutes(router: Router, deps: GithubAgentDeps): void {
  router.post('/webhook', async (req: Request, res: Response) => {
    const raw: Buffer = (req as Request & { rawBody?: Buffer }).rawBody
      ?? (Buffer.isBuffer(req.body) ? req.body : Buffer.from(JSON.stringify(req.body ?? {})));
    if (!verifyGithubSignature(req.header('x-hub-signature-256'), raw, deps.secret)) {
      res.status(401).json({ error: 'invalid GitHub webhook signature' });
      return;
    }
    const eventName = req.header('x-github-event') ?? '';
    if (eventName === 'ping') { res.status(200).json({ ok: true, pong: true }); return; }
    if (eventName && !['issue_comment', 'pull_request_review_comment'].includes(eventName)) {
      res.status(202).json({ ok: true, handled: false, reason: `event ${eventName} ignored` });
      return;
    }
    let payload: unknown = req.body;
    if (Buffer.isBuffer(req.body)) {
      try { payload = JSON.parse(req.body.toString('utf8')); } catch { res.status(400).json({ error: 'invalid JSON body' }); return; }
    }
    try {
      const result = await handleGithubCommentWebhook(payload, deps);
      res.status(result.handled ? 202 : 200).json({ ok: true, ...result });
    } catch (err) {
      res.status(500).json({ error: err instanceof Error ? err.message : 'github agent failed' });
    }
  });
}
