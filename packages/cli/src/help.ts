// Usage text for the headless CLI.

export const VERSION = '0.1.0';

export const HELP_TEXT = [
  'kriyadot — headless CLI for KriyaDot',
  '',
  'Works against a running KriyaDot API server (local or remote). Auth uses the',
  'loopback token for a local API automatically; for a remote API run',
  '"kriyadot login" once or set KRIYADOT_TOKEN.',
  '',
  'Usage: kriyadot <command> [options]',
  '',
  'Chat:',
  '  chat <bot> [message] [--message m] [--session s] [--model m]',
  '      [--provider p] [--auto-approve] [--format text|json]',
  '      One-shot ask. With no message and a TTY stdin, starts an',
  '      interactive REPL (streaming, /help, /model, /quit). Reads the',
  '      message from stdin when piped: echo "hi" | kriyadot chat helper',
  '  run --bot <id> --message <text> [--format json|text]',
  '      Non-interactive one-shot for CI/scripts. Exit code 0 on success,',
  '      1 on failure; --format json prints a single JSON object.',
  '',
  'Bots:',
  '  bots list                          List bots',
  '  bots run <bot> "task"              Run one task with a bot (one-shot chat)',
  '',
  'Threads:',
  '  threads list [--bot <id>] [--limit n]   List chat threads',
  '  threads show <id> [--limit n]           Show a thread\u2019s messages',
  '  threads branch <id> --from <msgId> [--title t]',
  '      Fork a thread from a message into a new branch',
  '  threads delete <id> --yes              Delete a thread (also clears its',
  '      circuit-breaker state)',
  '',
  'Routines:',
  '  routines list                      List routines',
  '  routines run <id>                  Trigger a routine run now',
  '  routines runs <id> [--limit n]     List runs for a routine',
  '',
  'Teams:',
  '  team apply <file.json|file.md>      Apply a team manifest or markdown doc',
  '  team export <teamId> [--markdown]   Export a team (JSON or markdown)',
  '',
  'Server:',
  '  serve --port <n>                   Start the API server in the foreground',
  '',
  'Models & MCP:',
  '  models list                        List available models',
  '  mcp list                           List installed MCP servers + health',
  '',
  'Setup:',
  '  login [--api <url>] [--token <t>]  Save API URL + token to ~/.kriyadot/cli.json',
  '  config                             Show effective config (token masked)',
  '  config set api <url>               Set the API base URL',
  '  config set token <token>           Set the auth token',
  '  config get <key>                   Print one config value',
  '  config path                        Print the config file path',
  '',
  'Global flags:',
  '  --api <url>        API base URL (env KRIYADOT_API_URL)',
  '  --token <token>    Auth token (env KRIYADOT_TOKEN)',
  '  --format text|json Output format for list/show commands',
  '  -h, --help         Show this help',
  '  -V, --version      Print the version',
  '',
  'Examples:',
  '  kriyadot chat helper "summarize yesterday\u2019s notes"',
  '  echo "review this" | kriyadot chat coder --format json',
  '  kriyadot run --bot coder --message "list the workspace" --format json',
  '  kriyadot threads branch sess_abc --from 42 --title "alternate plan"',
].join('\n');

