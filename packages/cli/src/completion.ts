export interface DynamicNames {
  bots: string[];
  /** Workflow names — the CLI surface for workflows is routines. */
  workflows: string[];
}

export const EMPTY_DYNAMIC: DynamicNames = { bots: [], workflows: [] };

/**
 * Race a promise against a short timeout. The timer is unref'd so a
 * pending lookup never keeps the CLI process alive.
 */
export async function withTimeout<T>(p: Promise<T>, ms: number): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<never>((_resolve, reject) => {
    timer = setTimeout(() => reject(new Error(`timed out after ${ms}ms`)), ms);
    if (typeof timer === 'object' && typeof (timer as { unref?: unknown }).unref === 'function') {
      (timer as { unref: () => void }).unref();
    }
  });
  try {
    return await Promise.race([p, timeout]);
  } finally {
    if (timer !== undefined) clearTimeout(timer);
  }
}

/** Keep only tokens that are safe to embed unquoted in a word list. */
function safeTokens(names: readonly string[]): string[] {
  const seen = new Set<string>();
  for (const n of names) {
    const t = n.trim();
    if (/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(t)) seen.add(t);
  }
  return [...seen];
}

/** Single-quote a string for POSIX shells / zsh arrays. */
function sq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export function bashCompletionScript(dynamic: DynamicNames = EMPTY_DYNAMIC): string {
  const bots = safeTokens(dynamic.bots).join(' ');
  const workflows = safeTokens(dynamic.workflows).join(' ');
  const commands = COMPLETION_COMMANDS.join(' ');
  const subs = COMPLETION_SUBCOMMANDS.join(' ');
  const flags = COMPLETION_FLAGS.join(' ');
  return [
    '# bash completion for kriyadot — generated by `kriyadot completion bash`',
    '# Install: kriyadot completion bash > ~/.local/share/bash-completion/completions/kriyadot',
    `# Bots/workflows baked in from the API at generation time (may be empty offline).`,
    `_kriyadot_bots="${bots}"`,
    `_kriyadot_workflows="${workflows}"`,
    // Named sessions live in the local config store, not the API, so
    // they cannot be baked in here; the variable is a static extension point.
    `_kriyadot_sessions=""`,
    '_kriyadot() {',
    '  local cur prev cmd',
    '  COMPREPLY=()',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
    '  cmd="${COMP_WORDS[1]:-}"',
    '  case "$prev" in',
    '    --bot) COMPREPLY=( $(compgen -W "$_kriyadot_bots" -- "$cur") ); return 0 ;;',
    '    --format) COMPREPLY=( $(compgen -W "text json jsonl" -- "$cur") ); return 0 ;;',
    '    --session|--daemon) COMPREPLY=( $(compgen -W "$_kriyadot_sessions" -- "$cur") ); return 0 ;;',
    '    completion) COMPREPLY=( $(compgen -W "bash zsh" -- "$cur") ); return 0 ;;',
    '  esac',
    '  if [[ "$cur" == -* ]]; then',
    `    COMPREPLY=( $(compgen -W "${flags}" -- "$cur") ); return 0`,
    '  fi',
    '  if [[ $COMP_CWORD -eq 1 ]]; then',
    `    COMPREPLY=( $(compgen -W "${commands}" -- "$cur") ); return 0`,
    '  fi',
    '  case "$cmd" in',
    '    chat) COMPREPLY=( $(compgen -W "$_kriyadot_bots" -- "$cur") ) ;;',
    '    routines)',
    '      if [[ $COMP_CWORD -ge 3 ]]; then',
    '        COMPREPLY=( $(compgen -W "$_kriyadot_workflows" -- "$cur") )',
    '      else',
    `        COMPREPLY=( $(compgen -W "${subs}" -- "$cur") )`,
    '      fi ;;',
    `    bots|threads|team|tap|models|mcp|config|sessions|pause|bridge|learning|daemon) COMPREPLY=( $(compgen -W "${subs}" -- "$cur") ) ;;`,
    '  esac',
    '  return 0',
    '}',
    'complete -F _kriyadot kriyadot',
    '',
  ].join('\n');
}

export function zshCompletionScript(dynamic: DynamicNames = EMPTY_DYNAMIC): string {
  const bots = safeTokens(dynamic.bots);
  const workflows = safeTokens(dynamic.workflows);
  const cmdSpecs = COMPLETION_COMMANDS.map((c) => `${c}:${c} command`);
  return [
    '#compdef kriyadot',
    '# zsh completion for kriyadot — generated by `kriyadot completion zsh`',
    '# Install: kriyadot completion zsh > "${fpath[1]}/_kriyadot"',
    '# Bots/workflows baked in from the API at generation time (may be empty offline).',
    '',
    '_kriyadot_commands() {',
    '  local -a commands',
    '  commands=(',
    ...cmdSpecs.map((s) => `    ${sq(s)}`),
    '  )',
    '  _describe -t commands "kriyadot command" commands',
    '}',
    '',
    '_kriyadot_bots() {',
    '  local -a bots',
    `  bots=(${bots.map(sq).join(' ')})`,
    '  _describe -t bots "bot" bots',
    '}',
    '',
    '_kriyadot_workflows() {',
    '  local -a workflows',
    `  workflows=(${workflows.map(sq).join(' ')})`,
    '  _describe -t workflows "workflow (routine)" workflows',
    '}',
    '',
    '_kriyadot() {',
    '  local context state line',
    '  _arguments -C \\',
    "    '--api[API base URL]:url:' \\",
    "    '--token[Auth token]:token:' \\",
    "    '--format[Output format]:format:(text json jsonl)' \\",
    "    '(-c)-c[Per-run config override key=value]:override:' \\",
    "    '--bot[Bot id]:bot:_kriyadot_bots' \\",
    "    '--message[Message text]:message:' \\",
    "    '--session[Session id or named session]:session:' \\",
    "    '--daemon[Record the run under a named session]:name:' \\",
    "    '--model[Model id]:model:' \\",
    "    '--provider[Provider id]:provider:' \\",
    "    '--auto-approve[Auto-approve tool calls]' \\",
    "    '(-h --help)'{-h,--help}'[Show help]' \\",
    "    '(-V --version)'{-V,--version}'[Print version]' \\",
    "    '1:command:_kriyadot_commands' \\",
    "    '*::arg:_kriyadot_subcommand'",
    '}',
    '',
    '_kriyadot_subcommand() {',
    '  case "${words[1]}" in',
    '    chat) _kriyadot_bots ;;',
    '    routines)',
    '      if (( CURRENT >= 3 )); then _kriyadot_workflows; else _arguments "1:subcommand:(list run runs)"; fi ;;',
    '    bots) _arguments "1:subcommand:(list run)" ;;',
    '    threads) _arguments "1:subcommand:(list show branch delete)" ;;',
    '    sessions) _arguments "1:subcommand:(list delete)" ;;',
    '    team) _arguments "1:subcommand:(apply export)" ;;',
    '    tap) _arguments "1:subcommand:(init install validate)" ;;',
    '    bridge) _arguments "1:subcommand:(invite link list peers experts chat unlink)" ;;',
    '    learning) _arguments "1:subcommand:(list show delete clear evolution)" ;;',
    '    daemon) _arguments "1:subcommand:(start list stop)" ;;',
    '    models|mcp) _arguments "1:subcommand:(list)" ;;',
    '    config) _arguments "1:subcommand:(get set path validate init)" ;;',
    '    completion) _arguments "1:shell:(bash zsh)" ;;',
    '  esac',
    '}',
    '',
    '_kriyadot "$@"',
    '',
  ].join('\n');
}
