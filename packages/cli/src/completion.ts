// Shell completion scripts for bash and zsh (`kriyadot completion`).
//
// Subcommands and flags are completed statically from the tables below.
// Bot names and workflow (routine) names are completed dynamically: the
// `completion` command fetches them from the API when it is reachable and
// bakes them into the printed script; when the API is unreachable the
// script silently falls back to the static surface only — generating a
// completion script must never crash or hang on a dead server, so the
// fetch is capped by COMPLETION_API_TIMEOUT_MS.

